def load_fold_map(json_path: str) -> Dict[str, str]:
    """Build {subject_id -> fold_name} from subjects_in_each_fold.json."""
    with open(json_path) as f:
        d = json.load(f)
    return {s: fold for fold, info in d.items() for s in info.get('test', [])}


# ============================================================================
# Per-subject volume-level quality metrics (cached on disk)
# ============================================================================

def _compute_volume_metrics_for_subject(sub: str, df_merged: pd.DataFrame,
                                       loaders: Dict[str, callable]) -> Dict:
    """Returns a metric dict or raises."""
    norm_og, norm_recon, norm_asl = MOD01.get_putamen_normalization(df_merged, sub)
    if not all([norm_og, norm_recon, norm_asl]):
        raise ValueError("missing/zero putamen normalization")

    pet_og = loaders['pet'](sub) / norm_og
    pet_rc = loaders['flowgan'](sub) / norm_recon
    asl    = loaders['asl'](sub) / norm_asl
    if asl.ndim == 4:
        asl = asl[:, :, :, 0]

    m_rc = get_quality_metrics(pet_og, pet_rc)
    m_as = get_quality_metrics(pet_og, asl)
    return {
        'ssim_recon': m_rc['ssim'], 'psnr_recon': m_rc['psnr'],
        'rmse_recon': m_rc['rmse'], 'ncc_recon':  m_rc['ncc'],
        'ssim_asl':   m_as['ssim'], 'psnr_asl':   m_as['psnr'],
        'rmse_asl':   m_as['rmse'], 'ncc_asl':    m_as['ncc'],
    }


def compute_volume_metrics(cohort: str, df_merged: pd.DataFrame,
                           force_recompute: bool) -> pd.DataFrame:
    cache = os.path.join(TABLES_DIR, f'per_subject_quality_{cohort}.csv')
    if not force_recompute and os.path.exists(cache):
        print(f"  Loading cached per-subject quality from {cache}")
        return pd.read_csv(cache)

    if cohort == 'TLE':
        loaders = {'pet': MOD01.load_pet_tle, 'flowgan': MOD01.load_flowgan_tle,
                   'asl': MOD01.load_asl_tle}
    elif cohort == 'MCI':
        loaders = {'pet': MOD01.load_pet_mci, 'flowgan': MOD01.load_flowgan_mci,
                   'asl': MOD01.load_asl_mci}
    else:
        raise ValueError(cohort)

    subjects = df_merged['subject'].unique()
    rows = []
    for sub in tqdm(subjects, desc=f"{cohort} volume-level quality"):
        try:
            metrics = _compute_volume_metrics_for_subject(sub, df_merged, loaders)
            rows.append({'subject': sub, **metrics})
        except Exception as e:
            print(f"  skip {sub}: {e}")

    df = pd.DataFrame(rows)
    os.makedirs(TABLES_DIR, exist_ok=True)
    df.to_csv(cache, index=False)
    print(f"  Cached {len(df)} subjects to {cache}")
    return df


# ============================================================================
# Per-subject within-subject Spearman correlation across regions
# ============================================================================

def compute_within_subject_corr(df_merged: pd.DataFrame, analysis_type: str
                                ) -> pd.DataFrame:
    """One row per subject with (r_recon, r_asl).
    analysis_type='SUVR'        : Spearman across regions of putamen-normalized values.
    analysis_type='Asymmetry'   : Spearman across regions of AI = (L-R)/(L+R).
    """
    rows = []
    subjects = df_merged['subject'].unique()
    for sub in subjects:
        df_s = df_merged[df_merged['subject'] == sub].copy()

        # Putamen normalization for this subject
        sub_mask = df_s['subject'] == sub
        l_og = df_s[sub_mask & (df_s['region_name'] == 'Putamen') & (df_s['side'] == 'Left')]['value_pet_original'].values
        r_og = df_s[sub_mask & (df_s['region_name'] == 'Putamen') & (df_s['side'] == 'Right')]['value_pet_original'].values
        l_rc = df_s[sub_mask & (df_s['region_name'] == 'Putamen') & (df_s['side'] == 'Left')]['value_pet_recon'].values
        r_rc = df_s[sub_mask & (df_s['region_name'] == 'Putamen') & (df_s['side'] == 'Right')]['value_pet_recon'].values
        l_as = df_s[sub_mask & (df_s['region_name'] == 'Putamen') & (df_s['side'] == 'Left')]['value_asl'].values
        r_as = df_s[sub_mask & (df_s['region_name'] == 'Putamen') & (df_s['side'] == 'Right')]['value_asl'].values
        if not all(len(x) > 0 for x in (l_og, r_og, l_rc, r_rc, l_as, r_as)):
            continue
        norm_og = float(l_og[0] + r_og[0])
        norm_rc = float(l_rc[0] + r_rc[0])
        norm_as = float(l_as[0] + r_as[0])
        if not all([norm_og, norm_rc, norm_as]):
            continue

        df_s['_og']  = df_s['value_pet_original'] / norm_og
        df_s['_rc']  = df_s['value_pet_recon']    / norm_rc
        df_s['_asl'] = df_s['value_asl']          / norm_as

        if analysis_type == 'SUVR':
            d = df_s.dropna(subset=['_og', '_rc', '_asl'])
            d = d[~d['region_name'].isin(EXCLUDE_REGIONS)]
            if len(d) < 5:
                continue
            r_rc_val, _  = stats.spearmanr(d['_og'], d['_rc'])
            r_asl_val, _ = stats.spearmanr(d['_og'], d['_asl'])
        else:  # Asymmetry
            left  = df_s[df_s['side'] == 'Left'].set_index('region_name')
            right = df_s[df_s['side'] == 'Right'].set_index('region_name')
            common = [r for r in left.index
                      if r in right.index and r not in EXCLUDE_REGIONS]
            if len(common) < 5:
                continue
            left  = left.loc[common]
            right = right.loc[common]
            ai_og = ((left['_og']  - right['_og'])  /
                     (left['_og']  + right['_og'])).values
            ai_rc = ((left['_rc']  - right['_rc'])  /
                     (left['_rc']  + right['_rc'])).values
            ai_as = ((left['_asl'] - right['_asl']) /
                     (left['_asl'] + right['_asl'])).values
            valid = np.isfinite(ai_og) & np.isfinite(ai_rc) & np.isfinite(ai_as)
            if valid.sum() < 5:
                continue
            r_rc_val,  _ = stats.spearmanr(ai_og[valid], ai_rc[valid])
            r_asl_val, _ = stats.spearmanr(ai_og[valid], ai_as[valid])

        rows.append({'subject': sub,
                     'r_recon': float(r_rc_val) if r_rc_val == r_rc_val else np.nan,
                     'r_asl':   float(r_asl_val) if r_asl_val == r_asl_val else np.nan})
    return pd.DataFrame(rows)


