"""
Script 10: Per-FlowGAN-Fold Quality Metrics + Holdout (Reviewer Response)

Reviewer-driven companion to 01_quality_metrics.py and 02_regional_analysis.py.
It does NOT retrain FlowGAN. Instead, it reorganizes the existing per-subject
quality metrics by the FlowGAN training fold each subject belonged to.

The reviewer asked for:
  * mean +- SD across the 12 (we use 10 dev) folds, not pooled aggregates.
  * a clear deployment story (ensemble of 12 fold models vs. one retrain).
  * an unseen holdout reported separately.

FlowGAN was trained 12-fold; each subject's synthetic PET in df_pet_merged*.pkl
was generated by a model that did NOT see them. Per user decision:
  * folds 0..9 = development (10 folds, used for per-fold mean +- SD)
  * folds 10, 11 = holdout (~17%, reported separately)

This script does NOT load the FlowGAN model checkpoints (those are shared as
GitHub artifacts separately). It works entirely from the already-generated
synthetic PET volumes and the regional values in df_pet_merged*.pkl.

Outputs:
  tables/10_per_fold_quality_metrics/
    per_subject_quality_with_fold_{TLE,MCI}.csv   (cached; one row per subject)
    cv_summary_{TLE,MCI}.csv                       (per-metric mean+-SD across 10 dev folds)
    holdout_summary_{TLE,MCI}.csv                  (per-metric mean+-SD across holdout subjects)
    combined_summary_{TLE,MCI}.csv                 (side-by-side CV vs. holdout)

  figures/10_per_fold_quality_metrics/
    dev_vs_holdout_recon_{TLE,MCI}.{pdf,png}       (Real vs Synthetic, 4 panels)
    dev_vs_holdout_asl_{TLE,MCI}.{pdf,png}         (Real vs ASL baseline)
    per_fold_strip_{TLE,MCI}.{pdf,png}             (per-fold means as strips)
"""

