def plot_dev_vs_holdout(df_subject: pd.DataFrame, panel_metrics: List[str],
                        title: str) -> plt.Figure:
    """For each panel metric, show dev fold-means (10 points) vs. holdout
    subject values (n_holdout points) as a strip + box."""
    fig, axes = plt.subplots(1, len(panel_metrics),
                             figsize=(4.5 * len(panel_metrics), 5))
    if len(panel_metrics) == 1:
        axes = [axes]

    for ax, metric in zip(axes, panel_metrics):
        dev_fold_means = (df_subject[df_subject['split'] == 'dev']
                          .groupby('fold')[metric].mean()
                          .reindex(DEV_FOLDS).values)
        ho_vals = df_subject[df_subject['split'] == 'holdout'][metric].dropna().values

        long_rows = []
        for v in dev_fold_means:
            if np.isfinite(v):
                long_rows.append({'value': v, 'split': 'CV fold means (n=10)'})
        for v in ho_vals:
            long_rows.append({'value': v,
                              'split': f'Holdout subjects (n={len(ho_vals)})'})
        d = pd.DataFrame(long_rows)
        if d.empty:
            ax.set_visible(False)
            continue
        order = sorted(d['split'].unique())
        sns.boxplot(data=d, x='split', y='value', ax=ax,
                    order=order, width=0.5, palette=['#66c2a5', '#fc8d62'],
                    showfliers=False, linewidth=2)
        sns.stripplot(data=d, x='split', y='value', ax=ax, order=order,
                      color='black', size=5, alpha=0.7, jitter=0.15)
        ax.set_title(metric, fontweight='bold')
        ax.set_xlabel('')
        ax.set_ylabel(metric)
        sns.despine(ax=ax)
        # Rotate labels for readability
        ax.set_xticklabels(ax.get_xticklabels(), rotation=15, ha='right')

    fig.suptitle(title, fontweight='bold', y=1.02)
    plt.tight_layout()
    return fig


def plot_per_fold_strip(df_subject: pd.DataFrame, title: str) -> plt.Figure:
    """For the headline metric pair (within-subject Spearman r and SSIM),
    plot per-fold mean as a strip across the 10 dev folds with holdout band."""
    pairs = [
        ('r_recon',    'r_asl',    'Within-subject Spearman r'),
        ('ssim_recon', 'ssim_asl', 'SSIM'),
    ]
    fig, axes = plt.subplots(1, 2, figsize=(13, 5))

    for ax, (col_rc, col_as, panel_title) in zip(axes, pairs):
        dev = df_subject[df_subject['split'] == 'dev']
        ho  = df_subject[df_subject['split'] == 'holdout']

        fold_means_rc = (dev.groupby('fold')[col_rc].mean()
                            .reindex(DEV_FOLDS).values)
        fold_means_as = (dev.groupby('fold')[col_as].mean()
                            .reindex(DEV_FOLDS).values)

        x = np.arange(len(DEV_FOLDS))
        ax.scatter(x - 0.15, fold_means_rc, color='#1f77b4', s=70, alpha=0.85,
                   edgecolor='black', label='Synthetic (per-fold means)')
        ax.scatter(x + 0.15, fold_means_as, color='#ff7f0e', s=70, alpha=0.85,
                   edgecolor='black', label='ASL (per-fold means)')

        # Holdout reference: mean +/- SD as horizontal bands
        for vals, color, lbl in [
                (ho[col_rc].values, '#1f77b4', 'Synthetic holdout'),
                (ho[col_as].values, '#ff7f0e', 'ASL holdout')]:
            vals = vals[np.isfinite(vals)]
            if len(vals) == 0:
                continue
            m = vals.mean()
            sd = vals.std(ddof=1) if len(vals) > 1 else 0.0
            ax.axhline(m, color=color, linestyle='--', alpha=0.7, lw=2,
                       label=f'{lbl} mean={m:.2f}')
            ax.axhspan(m - sd, m + sd, color=color, alpha=0.10)

        ax.set_xticks(x)
        ax.set_xticklabels([f.replace('fold_', '') for f in DEV_FOLDS])
        ax.set_xlabel('Dev fold')
        ax.set_ylabel(panel_title, fontweight='bold')
        ax.set_title(panel_title, fontweight='bold')
        ax.legend(loc='best', fontsize=8)
        sns.despine(ax=ax)

    fig.suptitle(title, fontweight='bold', y=1.02)
    plt.tight_layout()
    return fig


