SCRIPT_DIR  = os.path.dirname(os.path.abspath(__file__))
FIGURES_DIR = os.path.join(SCRIPT_DIR, 'figures', '10_per_fold_quality_metrics')
TABLES_DIR  = os.path.join(SCRIPT_DIR, 'tables',  '10_per_fold_quality_metrics')

DEV_FOLDS     = [f'fold_{i}' for i in range(10)]
HOLDOUT_FOLDS = ['fold_10', 'fold_11']

FOLD_JSON_TLE = os.path.join(SCRIPT_DIR, 'data', 'subjects_in_each_fold_TLE.json')
FOLD_JSON_MCI = os.path.join(SCRIPT_DIR, 'data', 'subjects_in_each_fold_MCI.json')

# Excluded regions for within-subject correlation (consistent with 02_ and 05_)
EXCLUDE_REGIONS = ['unknown', 'bankssts', 'Unknown', 'vessel', 'VentralDC',
                   'temporalpole', 'frontalpole', 'corpuscallosum', 'Putamen']

# Metrics that benefit from being LOWER (e.g., RMSE) — for plot orientation
HIGHER_BETTER = {'ssim', 'psnr', 'ncc', 'r'}
LOWER_BETTER  = {'rmse'}


