# Per-fold aggregation
# ============================================================================

METRIC_COLS = ['ssim_recon', 'ssim_asl',
               'psnr_recon', 'psnr_asl',
               'rmse_recon', 'rmse_asl',
               'ncc_recon',  'ncc_asl',
               'r_recon',    'r_asl']


def attach_fold(df_subject: pd.DataFrame, fold_map: Dict[str, str]) -> pd.DataFrame:
    df = df_subject.copy()
    df['fold'] = df['subject'].map(fold_map)
    df['split'] = df['fold'].apply(
        lambda f: 'holdout' if f in HOLDOUT_FOLDS
                  else ('dev' if f in DEV_FOLDS else 'unknown'))
    return df


def _safe_mean_ci(values: np.ndarray) -> tuple:
    values = np.asarray(values, dtype=float)
    values = values[np.isfinite(values)]
    if len(values) == 0:
        return np.nan, np.nan, np.nan, np.nan
    m = float(np.mean(values))
    if len(values) < 2:
        return m, 0.0, m, m
    sd = float(np.std(values, ddof=1))
    if sd == 0.0:
        return m, 0.0, m, m
    _, lo, hi = mean_and_95ci(values)
    return m, sd, float(lo), float(hi)


def summarize_dev_folds(df_subject: pd.DataFrame) -> pd.DataFrame:
    """For each metric: compute one mean per dev fold (10 fold-means),
    then aggregate (mean +/- SD +/- 95% CI) across the fold-means.
    This is what the reviewer asked for."""
    rows = []
    dev = df_subject[df_subject['split'] == 'dev']
    for metric in METRIC_COLS:
        fold_means = (dev.groupby('fold')[metric]
                         .mean()
                         .reindex(DEV_FOLDS)  # ensures all 10 dev folds appear
                         .values)
        m, sd, lo, hi = _safe_mean_ci(fold_means)
        rows.append({
            'metric':       metric,
            'n_folds_used': int(np.isfinite(fold_means).sum()),
            'fold_mean':    m,
            'fold_sd':      sd,
            'fold_ci_low':  lo,
            'fold_ci_high': hi,
            'fold_means':   ';'.join('NA' if not np.isfinite(v) else f'{v:.4f}'
                                     for v in fold_means),
        })
    return pd.DataFrame(rows)


def summarize_holdout(df_subject: pd.DataFrame) -> pd.DataFrame:
    """Direct per-subject summary over the 2 holdout folds (treated as one set)."""
    rows = []
    ho = df_subject[df_subject['split'] == 'holdout']
    for metric in METRIC_COLS:
        m, sd, lo, hi = _safe_mean_ci(ho[metric].values)
        rows.append({
            'metric':            metric,
            'n_holdout_subjects': int(np.isfinite(ho[metric].values).sum()),
            'holdout_mean':       m,
            'holdout_sd':         sd,
            'holdout_ci_low':     lo,
            'holdout_ci_high':    hi,
        })
    return pd.DataFrame(rows)


