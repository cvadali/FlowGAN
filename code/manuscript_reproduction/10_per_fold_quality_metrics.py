# Cohort orchestration
# ============================================================================

def run_cohort(cohort: str, df_merged: pd.DataFrame, fold_map: Dict[str, str],
               force_recompute: bool):
    print(f"\n{'='*70}\n{cohort} - per-FlowGAN-fold quality metrics\n{'='*70}")

    # 1) Volume-level metrics (loads NIfTIs; cached on disk)
    df_q = compute_volume_metrics(cohort, df_merged, force_recompute)

    # 2) Within-subject Spearman correlation (cheap; recomputed each run)
    analysis_type = 'Asymmetry' if cohort == 'TLE' else 'SUVR'
    df_w = compute_within_subject_corr(df_merged, analysis_type)

    # 3) Merge per-subject metrics + fold tag
    df_subj = df_q.merge(df_w, on='subject', how='outer')
    df_subj = attach_fold(df_subj, fold_map)

    n_dev      = (df_subj['split'] == 'dev').sum()
    n_holdout  = (df_subj['split'] == 'holdout').sum()
    n_unknown  = (df_subj['split'] == 'unknown').sum()
    print(f"  Subjects: dev={n_dev}, holdout={n_holdout}, unknown_fold={n_unknown}")
    if n_unknown:
        unk = df_subj[df_subj['split'] == 'unknown']['subject'].tolist()
        print(f"    (unknown fold: {unk[:5]}{'...' if len(unk) > 5 else ''})")

    save_table(df_subj, f'per_subject_quality_with_fold_{cohort}', TABLES_DIR)

    # 4) Per-fold summary
    dev_sum = summarize_dev_folds(df_subj)
    ho_sum  = summarize_holdout(df_subj)
    save_table(dev_sum, f'cv_summary_{cohort}', TABLES_DIR)
    save_table(ho_sum,  f'holdout_summary_{cohort}', TABLES_DIR)

    # Print headline numbers
    print(f"\n  CV (10 dev folds): per-metric mean +/- SD over fold-means")
    for _, row in dev_sum.iterrows():
        print(f"    {row['metric']:<12} {row['fold_mean']:+.3f} +/- {row['fold_sd']:.3f}  "
              f"(95% CI [{row['fold_ci_low']:+.3f}, {row['fold_ci_high']:+.3f}])")
    print(f"\n  Holdout ({n_holdout} subjects): direct per-subject mean +/- SD")
    for _, row in ho_sum.iterrows():
        print(f"    {row['metric']:<12} {row['holdout_mean']:+.3f} +/- {row['holdout_sd']:.3f}  "
              f"(95% CI [{row['holdout_ci_low']:+.3f}, {row['holdout_ci_high']:+.3f}])")

    # 5) Combined side-by-side table for the manuscript
    combined = dev_sum.merge(ho_sum, on='metric', how='outer')
    save_table(combined, f'combined_summary_{cohort}', TABLES_DIR)

    # 6) Figures
    fig = plot_dev_vs_holdout(df_subj,
                              ['ssim_recon', 'psnr_recon', 'ncc_recon', 'r_recon'],
                              f'{cohort}: Real vs Synthetic FlowGAN')
    save_figure(fig, f'dev_vs_holdout_recon_{cohort}', FIGURES_DIR)
    plt.close(fig)

    fig = plot_dev_vs_holdout(df_subj,
                              ['ssim_asl', 'psnr_asl', 'ncc_asl', 'r_asl'],
                              f'{cohort}: Real vs ASL (baseline)')
    save_figure(fig, f'dev_vs_holdout_asl_{cohort}', FIGURES_DIR)
    plt.close(fig)

    fig = plot_per_fold_strip(df_subj, f'{cohort}: per-fold means with holdout reference')
    save_figure(fig, f'per_fold_strip_{cohort}', FIGURES_DIR)
    plt.close(fig)

    return df_subj


