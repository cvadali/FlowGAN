def main():
    parser = argparse.ArgumentParser(
        description='Per-FlowGAN-fold quality metrics + holdout (reviewer response).')
    parser.add_argument('--force', action='store_true',
                        help='Recompute per-subject volume-level metrics from NIfTIs '
                             '(otherwise loads the cached per_subject_quality_*.csv).')
    parser.add_argument('--tle-only', action='store_true', help='Run only TLE.')
    parser.add_argument('--mci-only', action='store_true', help='Run only MCI.')
    args = parser.parse_args()

    os.makedirs(FIGURES_DIR, exist_ok=True)
    os.makedirs(TABLES_DIR,  exist_ok=True)

    if not args.mci_only:
        with open(os.path.join(SCRIPT_DIR, 'df_pet_merged.pkl'), 'rb') as f:
            df_tle = pickle.load(f)
        fold_map_tle = load_fold_map(FOLD_JSON_TLE)
        run_cohort('TLE', df_tle, fold_map_tle, args.force)

    if not args.tle_only:
        with open(os.path.join(SCRIPT_DIR, 'df_pet_merged_mci.pkl'), 'rb') as f:
            df_mci = pickle.load(f)
        fold_map_mci = load_fold_map(FOLD_JSON_MCI)
        run_cohort('MCI', df_mci, fold_map_mci, args.force)

    print("\n" + "=" * 70)
    print("Done.")
    print(f"Figures: {FIGURES_DIR}")
    print(f"Tables:  {TABLES_DIR}")
    print("=" * 70)


if __name__ == '__main__':
    main()
